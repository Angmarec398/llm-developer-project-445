"""Редактор: собирает финальный ответ абоненту из докладов агентов.

Единственный агент, чей текст уходит пользователю.
"""
from __future__ import annotations

from agents import Agent

from app.llm import build_agent
from app.sessions import Session

EDITOR_PROMPT = """Ты — редактор ответов ассистента мобильного оператора.
Ты единственный, кого видит абонент: собери финальный ответ из докладов
доменных агентов.

Правила ответа:
- кратко, по-русски, дружелюбно;
- только факты из докладов агентов — ничего не выдумывай и не добавляй
  от себя;
- если в докладах есть источники базы знаний (источник: <source>) —
  обязательно назови их в ответе;
- если доклады противоречат друг другу или данных не хватает — честно
  скажи об этом, не сглаживай;
- если докладов нет вовсе — ответь на сообщение абонента сам, в рамках
  тем мобильного оператора.
"""


def build_editor(session: Session) -> Agent:
    """Собрать агента-редактора: без инструментов, только текст.

    Параметр session оставлен в сигнатуре на будущее: с этапа guardrail
    редактору понадобится состояние сессии.
    """
    return build_agent(name="editor", instructions=EDITOR_PROMPT)


def editor_task(message: str, runs: list[tuple[str, str]]) -> str:
    """Склеить сообщение абонента и доклады агентов в задачу редактору.

    runs — список пар (id агента, доклад) в порядке исполнения плана.
    """
    parts = [f"Сообщение абонента: {message}", "", "Доклады агентов:"]
    if runs:
        for position, (agent_id, report) in enumerate(runs, start=1):
            parts.append(f"{position}. [{agent_id}] {report}")
    else:
        parts.append("(докладов нет)")
    parts.append("")
    parts.append("Напиши ответ абоненту строго по этим фактам.")
    return "\n".join(parts)
